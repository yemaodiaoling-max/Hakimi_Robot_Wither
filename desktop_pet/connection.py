"""How the desktop pet reaches its server side (``desktop_pet_agent.py --serve``).

``desktop_pet/pet_connection.json`` (generated by the setup panel, 桌宠 section):

    {"mode": "local"}
        The bot runs on this same computer: the agent is started as a local child process.

    {"mode": "ssh", "host": "example.org", "port": 22, "user": "bot",
     "identity": "%USERPROFILE%\\.ssh\\id_ed25519", "known_hosts": "",
     "remote_command": "HAKIMI_ROOT=/opt/hakimi/instance /opt/hakimi/venv/bin/python -u /opt/hakimi/app/desktop_pet_agent.py"}
        The bot runs on a server: one persistent, windowless SSH session carries the JSONL protocol.

Without the file the pet uses local mode.
"""
from __future__ import annotations

import json
import os
import shutil
import sys
from pathlib import Path

PET_DIR = Path(__file__).resolve().parent
CONFIG_PATH = Path(os.environ.get("HAKIMI_PET_CONNECTION", "") or PET_DIR / "pet_connection.json")


def load() -> dict:
    try:
        value = json.loads(CONFIG_PATH.read_text(encoding="utf-8-sig"))
        return value if isinstance(value, dict) else {"mode": "local"}
    except (OSError, ValueError):
        return {"mode": "local"}


def _ssh_exe() -> str:
    candidates = [shutil.which("ssh"), r"C:\Windows\System32\OpenSSH\ssh.exe"]
    return next((c for c in candidates if c and Path(c).exists()), "ssh")


def command(serve: bool = True) -> list[str]:
    cfg = load()
    if cfg.get("mode") != "ssh":
        agent = PET_DIR.parent / "desktop_pet_agent.py"
        return [sys.executable, "-u", str(agent)] + (["--serve"] if serve else [])
    remote = str(cfg.get("remote_command") or "python3 -u desktop_pet_agent.py") + (" --serve" if serve else "")
    cmd = [_ssh_exe(), "-T", "-p", str(int(cfg.get("port") or 22)),
           "-o", "BatchMode=yes", "-o", "ConnectTimeout=10",
           "-o", "ServerAliveInterval=20", "-o", "ServerAliveCountMax=3"]
    if cfg.get("identity"):
        cmd += ["-i", os.path.expandvars(os.path.expanduser(str(cfg["identity"]))), "-o", "IdentitiesOnly=yes"]
    if cfg.get("known_hosts"):
        cmd += ["-o", "StrictHostKeyChecking=yes",
                "-o", "UserKnownHostsFile=" + os.path.expandvars(os.path.expanduser(str(cfg["known_hosts"])))]
    else:
        cmd += ["-o", "StrictHostKeyChecking=accept-new"]
    if cfg.get("kex"):
        cmd += ["-o", "KexAlgorithms=" + str(cfg["kex"])]
    target = str(cfg.get("host", ""))
    if cfg.get("user") and "@" not in target:
        target = f"{cfg['user']}@{target}"
    return cmd + [target, remote]
