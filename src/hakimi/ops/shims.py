"""Small generated entry files at historical script paths.

The code lives in the installed package, but some callers run a script by
path: the models execute ``python qq_cli.py call ...`` inside the bot lane
folder, and operator tools on Windows run ``<root>/cloud_activity.py`` and
``<root>/cloud_supervisor.py --report`` over SSH.  Each shim pins the data
folder to its own location (as the old code copy did) and runs the module.
"""
from pathlib import Path

from hakimi import paths

MARK = "# hakimi-shim"
TEMPLATE = '''{mark} (generated by hakimi.ops.shims; edit the package, not this file)
import os, runpy, sys
from pathlib import Path
_here = Path(__file__).resolve().parent
os.environ["HAKIMI_BASE"] = str(_here)
os.environ["HAKIMI_ROOT"] = str(_here.parent if _here.name == {runtime_name!r} else _here)
if {src!r} not in sys.path:
    sys.path.insert(1, {src!r})
runpy.run_module({module!r}, run_name="__main__", alter_sys=True)
'''
RUNTIME_SHIMS = {"qq_cli.py": "hakimi.tools.qq_cli"}
ROOT_SHIMS = {"qq_cli.py": "hakimi.tools.qq_cli",
              "cloud_activity.py": "hakimi.ops.cloud_activity",
              "cloud_supervisor.py": "hakimi.ops.cloud_supervisor"}


def render(module):
    return TEMPLATE.format(mark=MARK, runtime_name=paths.RUNTIME_NAME,
                           src=str(paths.PACKAGE_DIR.parent), module=module)


def write(folder, shims):
    folder = Path(folder)
    written = []
    for name, module in shims.items():
        target = folder / name
        text = render(module)
        if target.exists() and target.read_text(encoding="utf-8", errors="replace") == text:
            continue
        tmp = target.with_suffix(".shim.tmp")
        tmp.write_text(text, encoding="utf-8")
        tmp.replace(target)
        written.append(str(target))
    return written


def install(root=None, runtime=None):
    root = Path(root) if root else paths.root()
    runtime = Path(runtime) if runtime else root / paths.RUNTIME_NAME
    return write(root, ROOT_SHIMS) + (write(runtime, RUNTIME_SHIMS) if runtime.is_dir() else [])


if __name__ == "__main__":
    import argparse, json
    parser = argparse.ArgumentParser(description="write historical entry shims")
    parser.add_argument("--root")
    args = parser.parse_args()
    print(json.dumps(install(args.root), ensure_ascii=False))
